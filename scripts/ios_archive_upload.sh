#!/usr/bin/env bash
#
# Build a signed App Store IPA from this Flutter project and (optionally)
# upload it to App Store Connect / TestFlight.
#
# Run this on the macOS build machine, from the repo root:
#
#   ./scripts/ios_archive_upload.sh              # build + upload (if credentials found)
#   ./scripts/ios_archive_upload.sh --no-upload  # build only
#   ./scripts/ios_archive_upload.sh --clean      # flutter clean first
#
# Credentials for the upload step, either:
#   * App Store Connect API key:  ASC_KEY_ID / ASC_ISSUER_ID, key file at
#     ~/.appstoreconnect/private_keys/AuthKey_<KEY_ID>.p8
#   * or just let Xcode/Transporter do it manually afterwards (use --no-upload).
#
# Prerequisites, once per machine:
#   xcode-select --install
#   sudo xcodebuild -license accept
#   Xcode -> Settings -> Accounts -> add the Apple ID (creates the signing cert)
#   flutter config --no-enable-swift-package-manager   (CocoaPods only, see below)
#
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

DO_UPLOAD=1
DO_CLEAN=0
for arg in "$@"; do
  case "$arg" in
    --no-upload) DO_UPLOAD=0 ;;
    --clean)     DO_CLEAN=1 ;;
    *) echo "Unknown argument: $arg" >&2; exit 2 ;;
  esac
done

say() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
die() { printf '\n\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- preflight --
say "Preflight"

command -v flutter >/dev/null || die "flutter not found in PATH"
command -v xcodebuild >/dev/null || die "xcodebuild not found — install Xcode"
[ "$(uname -s)" = "Darwin" ] || die "iOS builds require macOS"

BUNDLE_ID="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleIdentifier' ios/Runner/Info.plist 2>/dev/null || true)"
PROJECT_BUNDLE_ID="$(grep -m1 'PRODUCT_BUNDLE_IDENTIFIER = ' ios/Runner.xcodeproj/project.pbxproj | sed 's/.*= //; s/;//' | tr -d ' ')"
echo "Bundle id in project : $PROJECT_BUNDLE_ID"

case "$PROJECT_BUNDLE_ID" in
  com.example.*) die "Bundle id is still the com.example placeholder. Set it in Xcode (Runner target -> Signing & Capabilities -> Bundle Identifier) or run scripts/set_ios_signing.ps1 on Windows, then re-run." ;;
esac

# Team id: prefer an explicit env var, else read what Xcode wrote into the
# project when you picked the team in Signing & Capabilities.
TEAM_ID="${TEAM_ID:-$(grep -m1 'DEVELOPMENT_TEAM = ' ios/Runner.xcodeproj/project.pbxproj | sed 's/.*= //; s/;//' | tr -d ' ' || true)}"
if [ -z "$TEAM_ID" ]; then
  die "No Apple Developer Team ID found. Open ios/Runner.xcworkspace, select the Runner target -> Signing & Capabilities -> Team, then re-run. (Or export TEAM_ID=ABCDE12345.)"
fi
echo "Team id              : $TEAM_ID"

# ExportOptions.plist is generated, not committed: it is derived from the value
# above, so there is exactly one source of truth for the team.
if [ ! -f ios/ExportOptions.plist ] || ! grep -q "<string>$TEAM_ID</string>" ios/ExportOptions.plist 2>/dev/null; then
  say "Writing ios/ExportOptions.plist for team $TEAM_ID"
  cat > ios/ExportOptions.plist <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by scripts/ios_archive_upload.sh - do not commit, it is machine specific. -->
<plist version="1.0">
<dict>
	<key>method</key>
	<string>app-store</string>
	<key>teamID</key>
	<string>$TEAM_ID</string>
	<key>signingStyle</key>
	<string>automatic</string>
	<key>uploadSymbols</key>
	<true/>
	<key>destination</key>
	<string>upload</string>
</dict>
</plist>
EOF
fi

# The project must not reference a Swift package for the Flutter plugins: the
# generated FlutterGeneratedPluginSwiftPackage keeps resolving a stale plugin set
# (it pulled 11 frameworks instead of 6 and produced a broken archive). We use
# CocoaPods exclusively.
if grep -q 'FlutterGeneratedPluginSwiftPackage' ios/Runner.xcodeproj/project.pbxproj; then
  say "Removing Flutter SPM plugin package from the Xcode project"
  python3 scripts/remove_spm_from_xcode.py || die "remove_spm_from_xcode.py failed"
fi

if ! grep -q 'PrivacyInfo.xcprivacy' ios/Runner.xcodeproj/project.pbxproj; then
  say "Adding PrivacyInfo.xcprivacy to the Xcode project"
  python3 scripts/add_privacy_manifest_to_xcode.py || die "add_privacy_manifest_to_xcode.py failed"
fi

# ------------------------------------------------------------------- build --
if [ "$DO_CLEAN" = "1" ]; then
  say "flutter clean"
  flutter clean
fi

say "flutter pub get"
flutter pub get

say "pod install"
( cd ios && pod install )

VERSION="$(grep -m1 '^version:' pubspec.yaml | sed 's/version: //')"
say "Building release IPA (version $VERSION)"

# `flutter build ipa` archives with xcodebuild and then exports using our
# ExportOptions.plist. Automatic signing needs -allowProvisioningUpdates, which
# Flutter passes through only in recent SDKs; if signing fails here, open
# ios/Runner.xcworkspace once in Xcode and let it register the App ID.
flutter build ipa --release --export-options-plist=ios/ExportOptions.plist

IPA="$(ls -t build/ios/ipa/*.ipa 2>/dev/null | head -1 || true)"
[ -n "$IPA" ] || die "No IPA produced — check the build log above"
echo "IPA: $IPA ($(du -h "$IPA" | cut -f1))"

# ------------------------------------------------------------------ upload --
if [ "$DO_UPLOAD" = "1" ] && [ -n "${ASC_KEY_ID:-}" ] && [ -n "${ASC_ISSUER_ID:-}" ]; then
  say "Uploading to App Store Connect (altool)"
  xcrun altool --upload-app -f "$IPA" -t ios \
    --apiKey "$ASC_KEY_ID" --apiIssuer "$ASC_ISSUER_ID"
  echo "Upload finished. Wait for processing in App Store Connect, then attach the build to TestFlight."
else
  say "Skipping upload"
  cat <<EOF
Next steps, either:
  * Xcode -> Window -> Organizer -> Distribute App -> App Store Connect -> Upload
    (the archive is already in ~/Library/Developer/Xcode/Archives)
  * or upload this IPA with the Transporter app
  * or re-run with ASC_KEY_ID / ASC_ISSUER_ID set to upload from the CLI
EOF
fi
